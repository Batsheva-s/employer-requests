/// <summary>Builds requests for tests without a database.</summary>
internal static class TestRequests
{
    public static ServiceRequest Create(int id, RequestStatus status, byte[] rowVersion)
    {
        var request = new ServiceRequest(
            "בירור תשלום", "אלון תעשיות בע\"מ", RequestPriority.Medium, "שרה כהן",
            new DateTimeOffset(2026, 1, 1, 8, 0, 0, TimeSpan.Zero), status);

        // Id and RowVersion are generated by the database. Without a database, the test sets them directly.
        typeof(ServiceRequest).GetProperty(nameof(ServiceRequest.Id))!.SetValue(request, id);
        typeof(ServiceRequest).GetProperty(nameof(ServiceRequest.RowVersion))!.SetValue(request, rowVersion);
        return request;
    }
}

/// <summary>
/// An in-memory repository for testing the status logic. It can simulate the case only the database can detect:
/// the request was changed by someone else between our read and our save.
/// </summary>
internal sealed class FakeRequestRepository : IRequestRepository
{
    private readonly Dictionary<int, ServiceRequest> _requests = [];
    private ServiceRequest? _lastLoaded;

    /// <summary>Saving this request fails as if another user had saved it first.</summary>
    public int? ConflictOnSaveForId { get; init; }

    public int SuccessfulSaves { get; private set; }

    public ServiceRequest Add(ServiceRequest request)
    {
        _requests[request.Id] = request;
        return request;
    }

    public Task<ServiceRequest?> GetForUpdateAsync(int id, CancellationToken cancellationToken)
    {
        _lastLoaded = _requests.GetValueOrDefault(id);
        return Task.FromResult(_lastLoaded);
    }

    public Task SaveChangesAsync(CancellationToken cancellationToken)
    {
        if (_lastLoaded is not null && _lastLoaded.Id == ConflictOnSaveForId)
        {
            throw new ConcurrencyConflictException(_lastLoaded.Id);
        }

        SuccessfulSaves++;
        return Task.CompletedTask;
    }

    // The status logic does not read lists, history or counts.
    public Task<PagedResult<RequestListItemDto>> SearchAsync(RequestSearchQuery query, CancellationToken cancellationToken) => throw new NotSupportedException();
    public Task<ServiceRequest?> FindAsync(int id, CancellationToken cancellationToken) => throw new NotSupportedException();
    public Task<bool> ExistsAsync(int id, CancellationToken cancellationToken) => throw new NotSupportedException();
    public Task<IReadOnlyList<RequestStatusChangeDto>> GetHistoryAsync(int requestId, CancellationToken cancellationToken) => throw new NotSupportedException();
    public Task<IReadOnlyList<StatusPriorityCount>> CountByStatusAndPriorityAsync(RequestFilter filter, CancellationToken cancellationToken) => throw new NotSupportedException();
    public Task<IReadOnlyList<AssigneeWorkloadDto>> GetTopAssigneesAsync(RequestFilter filter, int count, CancellationToken cancellationToken) => throw new NotSupportedException();
}

/// <summary>A cache that never caches and counts invalidations.</summary>
internal sealed class CountingSummaryCache : ISummaryCache
{
    public int Invalidations { get; private set; }

    public Task<RequestsSummaryDto> GetOrCalculateAsync(Func<CancellationToken, Task<RequestsSummaryDto>> calculate, CancellationToken cancellationToken) =>
        calculate(cancellationToken);

    public void Invalidate() => Invalidations++;
}

