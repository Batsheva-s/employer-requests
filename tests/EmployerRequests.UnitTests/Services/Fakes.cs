namespace EmployerRequests.UnitTests.Services;

/// <summary>Builds requests for tests without a database.</summary>
internal static class TestRequests
{
    public static ServiceRequest Create(int id, RequestStatus status, byte[] rowVersion)
    {
        var request = new ServiceRequest(
            "בירור תשלום",
            "אלון תעשיות בע\"מ",
            RequestPriority.Medium,
            "שרה כהן",
            new DateTimeOffset(2026, 1, 1, 8, 0, 0, TimeSpan.Zero),
            status);

        // Id and RowVersion are generated by the database, so their setters are private.
        // Without a database, the test sets them through reflection.
        SetProperty(request, nameof(ServiceRequest.Id), id);
        SetProperty(request, nameof(ServiceRequest.RowVersion), rowVersion);
        return request;
    }

    private static void SetProperty(ServiceRequest request, string propertyName, object value)
    {
        var property = typeof(ServiceRequest).GetProperty(propertyName);
        if (property == null)
        {
            throw new InvalidOperationException($"ServiceRequest has no property named {propertyName}.");
        }

        property.SetValue(request, value);
    }
}

/// <summary>
/// An in-memory repository for testing the status logic. It can simulate the case only the database can detect:
/// the request was changed by someone else between our read and our save.
/// </summary>
internal sealed class FakeRequestRepository : IRequestRepository
{
    private readonly Dictionary<int, ServiceRequest> _requests = new Dictionary<int, ServiceRequest>();
    private ServiceRequest? _lastLoaded;

    /// <summary>Saving this request fails as if another user had saved it first.</summary>
    public int? ConflictOnSaveForId { get; set; }

    /// <summary>Saving this request fails with an unexpected error, as when the database does not answer in time.</summary>
    public int? FailOnSaveForId { get; set; }

    public int SuccessfulSaves { get; private set; }

    public ServiceRequest Add(ServiceRequest request)
    {
        _requests[request.Id] = request;
        return request;
    }

    public Task<ServiceRequest?> GetForUpdateAsync(int id, CancellationToken cancellationToken)
    {
        // The request with this id, or null if there is none.
        _lastLoaded = _requests.GetValueOrDefault(id);
        return Task.FromResult(_lastLoaded);
    }

    public Task SaveChangesAsync(CancellationToken cancellationToken)
    {
        if (_lastLoaded != null && _lastLoaded.Id == ConflictOnSaveForId)
        {
            throw new ConcurrencyConflictException(_lastLoaded.Id);
        }

        if (_lastLoaded != null && _lastLoaded.Id == FailOnSaveForId)
        {
            throw new TimeoutException("The database did not answer in time.");
        }

        SuccessfulSaves++;
        return Task.CompletedTask;
    }

    // ---------- The status logic does not read lists, history or counts ----------

    public Task<PagedResultDto<RequestListItemDto>> SearchAsync(RequestSearchDto search, CancellationToken cancellationToken)
    {
        throw new NotSupportedException();
    }

    public Task<ServiceRequest?> GetByIdAsync(int id, CancellationToken cancellationToken)
    {
        throw new NotSupportedException();
    }

    public Task<bool> ExistsAsync(int id, CancellationToken cancellationToken)
    {
        throw new NotSupportedException();
    }

    public Task<IReadOnlyList<RequestStatusChangeDto>> GetHistoryAsync(int requestId, CancellationToken cancellationToken)
    {
        throw new NotSupportedException();
    }

    public Task<IReadOnlyList<StatusPriorityCount>> CountByStatusAndPriorityAsync(RequestFilterDto filter, CancellationToken cancellationToken)
    {
        throw new NotSupportedException();
    }

    public Task<IReadOnlyList<AssigneeWorkloadDto>> GetTopAssigneesAsync(RequestFilterDto filter, int count, CancellationToken cancellationToken)
    {
        throw new NotSupportedException();
    }
}
